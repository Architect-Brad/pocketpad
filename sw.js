/* PocketPad service worker — full offline precaching */
importScripts('./sw-cache.js');

const CACHE = 'pocketpad-v3';
const CDN_CACHE = 'pocketpad-cdn-v1';

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PP_PRECACHE_URLS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => k !== CACHE && k !== CDN_CACHE)
            .map((k) => caches.delete(k))
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  const sameOrigin = url.origin === self.location.origin;

  if (sameOrigin) {
    const path = url.pathname;
    const isAppShell =
      req.mode === 'navigate' ||
      path === '/' ||
      path.endsWith('.html') ||
      path.endsWith('/sw.js') ||
      path.endsWith('/sw-cache.js') ||
      path.endsWith('/manifest.json') ||
      path.startsWith('/lib/');

    if (isAppShell) {
      // Network-first so deploys aren't stuck behind a stale PWA cache
      event.respondWith(
        fetch(req)
          .then((res) => {
            if (res && res.status === 200) {
              const copy = res.clone();
              caches.open(CACHE).then((cache) => cache.put(req, copy));
            }
            return res;
          })
          .catch(() =>
            caches.match(req).then((cached) => cached || caches.match('./index.html'))
          )
      );
      return;
    }

    // Cache-first for hashed / versioned vendor assets
    event.respondWith(
      caches.match(req).then((cached) => {
        if (cached) return cached;
        return fetch(req).then((res) => {
          if (res && res.status === 200) {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put(req, copy));
          }
          return res;
        });
      })
    );
    return;
  }

  // CDN / external: cache-first with network update
  event.respondWith(
    caches.match(req).then((cached) => {
      const fetched = fetch(req)
        .then((res) => {
          if (res && res.status === 200 && (res.type === 'basic' || res.type === 'cors')) {
            const copy = res.clone();
            caches.open(CDN_CACHE).then((cache) => cache.put(req, copy));
          }
          return res;
        })
        .catch(() => cached);
      return cached || fetched;
    })
  );
});
